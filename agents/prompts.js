// Промпты для каждого агента пайплайна recipe-finder.

function finderPrompt(category, count) {
  const wanted = count * 2;
  return `Ты finder в команде агентов recipe-finder. Найди ${wanted} простых рецептов по категории/теме: "${category}".
Требования к каждому рецепту:
- не больше 8 ингредиентов;
- никаких редких, экзотических или сложных в поиске продуктов;
- простые, понятные шаги приготовления.
По возможности отдавай предпочтение сайту ru.wikibooks.org (раздел «Поваренная книга») — но если подходящих рецептов там не хватает, дополни другими источниками из общего поиска.

Ответь СТРОГО в формате JSON, без markdown-разметки, без обёртки в код-блоки:
{
  "candidates": [
    { "title": "название блюда", "url": "ссылка на страницу с рецептом" }
  ]
}`;
}

