// Промпты для агентов пайплайна recipe-finder (сейчас — кулинарные лайфхаки/советы).

function finderPrompt(category, count) {
  const wanted = count * 2;
  return `Ты finder в команде агентов recipe-finder. Найди ${wanted} практических кулинарных лайфхаков/советов по теме: "${category}".
Требования к каждому:
- конкретный практический приём, а не общие слова («готовьте с любовью» не подходит);
- один чёткий совет на кандидата (если это подборка из нескольких лайфхаков — укажи ссылку на страницу, а конкретный пункт выберет следующий агент);
- понятно и применимо на обычной домашней кухне, без специального оборудования.

Ответь СТРОГО в формате JSON, без markdown-разметки, без обёртки в код-блоки:
{
  "candidates": [
    { "title": "краткая суть совета", "url": "ссылка на страницу с советом" }
  ]
}`;
}

// Берём только факт — сам совет как он изложен на странице, без пересказа своими
// словами и без придуманного личного вступления. Практический приём/факт сам по
// себе не является объектом авторского права, поэтому лицензия источника тут не
// нужна — в отличие от фото, которое всегда берётся отдельно и лицензионно чисто
// (см. agents/openverse.js).
function extractPrompt(url) {
  return `Ты extractor в команде агентов recipe-finder. Открой страницу по ссылке (инструмент WebFetch): ${url}

Найди на странице один конкретный кулинарный лайфхак/совет (если их несколько — выбери самый практичный и самодостаточный) и извлеки его как факт, без пересказа своими словами и без добавления вступления/истории от себя:
- короткий заголовок сути совета;
- сам совет: что делать и почему это работает (2-5 предложений, как на странице — формулировки можно немного сократить для читаемости, но не менять суть и не дописывать от себя);
- автора/источник, если явно указан (иначе null).

Также дай короткий поисковый запрос НА АНГЛИЙСКОМ для поиска иллюстрирующего фото (2-4 слова) — русскоязычные запросы на фотостоках почти не работают.

Ответь СТРОГО в формате JSON, без markdown-разметки, без обёртки в код-блоки:
{
  "title": "краткий заголовок совета",
  "body": "текст совета",
  "author": "автор или null",
  "imageQuery": "короткий запрос на английском, например 'fresh basil'"
}`;
}

module.exports = { finderPrompt, extractPrompt };
