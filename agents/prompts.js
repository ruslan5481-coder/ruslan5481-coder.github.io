function writerPrompt(sourceRecipe) {
  return `Ты writer в команде агентов recipe-finder. Перепиши рецепт своими словами для публикации на собственном сайте — так, чтобы формулировки были оригинальными, а не скопированными из источника.
Список ингредиентов и порядок шагов по сути сохрани (это не текст, а факт рецепта), но вступление и формулировки каждого шага напиши заново, своими словами.

Исходный рецепт: ${JSON.stringify(sourceRecipe, null, 2)}

Ответь СТРОГО в формате JSON, без markdown-разметки, без обёртки в код-блоки:
{
  "title": "заголовок (можно немного переформулировать)",
  "intro": "новое вступление своими словами (1-3 предложения)",
  "ingredients": ["ингредиент 1", "ингредиент 2"],
  "steps": ["переписанный шаг 1", "переписанный шаг 2"]
}`;
}

